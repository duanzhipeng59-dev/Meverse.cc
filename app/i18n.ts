export function t(
  dict: TranslationDict,
  key: string,
  params?: Record<string, string | number>,
): string {
  let value = dict[key] ?? key;
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      value = value.replace(`{${k}}`, String(v));
    }
  }
  return value;
}
